"use client";

import React, { useState, useRef } from "react";
import {
  Download,
  Printer,
  Copy,
  FileCode,
  Upload,
  Check,
  FileText,
} from "lucide-react";
import { useUtsav } from "@/hooks/useUtsavStore";
import { formatINR, calculateBudgetTotals } from "@/lib/budget/math";
import { formatDatePretty } from "@/lib/utils/date";

export function ExportSection() {
  const { activeEvent, saveNewEvent, addToast } = useUtsav();
  const [copiedSummary, setCopiedSummary] = useState(false);
  const fileInputRef = useRef<HTMLInputElement>(null);

  if (!activeEvent) return null;

  const totals = calculateBudgetTotals(activeEvent.categories, activeEvent.totalBudget);

  // Markdown Summary
  const generateMarkdownSummary = () => {
    return `
# ${activeEvent.name}
**Type:** ${activeEvent.type.toUpperCase()} | **Date:** ${formatDatePretty(activeEvent.date)} | **City:** ${activeEvent.city}
**Scale:** ${activeEvent.guestCount} Guests | **Total Budget:** ${formatINR(activeEvent.totalBudget)}
**Vibes:** ${activeEvent.vibe.join(", ")}

## Budget Summary
- **Allocated:** ${formatINR(totals.totalAllocated)}
- **Spent / Booked:** ${formatINR(totals.totalSpent)}
- **Remaining Buffer:** ${formatINR(totals.remaining)}

### Categories:
${activeEvent.categories
  .map(
    (c) =>
      `- **${c.name}**: ${formatINR(c.allocatedAmount)} (${c.allocatedPercent}%) | Spent: ${formatINR(c.spentAmount)}`,
  )
  .join("\n")}

## Key Timeline Milestones (${activeEvent.timeline.length} tasks)
${activeEvent.timeline
  .map(
    (t) =>
      `- [${t.completed ? "x" : " "}] **${t.title}** (${t.phase}, Due ${formatDatePretty(t.dueDate)}) - ${t.description}`,
  )
  .join("\n")}

## Booked & Recommended Vendors
${activeEvent.vendors
  .map(
    (v) =>
      `- **${v.name}** (${v.category}) - Status: ${v.status.toUpperCase()} | Quoted: ${formatINR(v.quotedPrice)}`,
  )
  .join("\n")}

---
*Generated by Utsav AI Celebration & Event Planner*
`.trim();
  };

  const handleCopySummary = () => {
    const md = generateMarkdownSummary();
    navigator.clipboard.writeText(md);
    setCopiedSummary(true);
    addToast({
      type: "success",
      title: "Summary Copied",
      message: "Markdown summary copied to clipboard.",
    });
    setTimeout(() => setCopiedSummary(false), 2000);
  };

  const handleDownloadJson = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(activeEvent, null, 2));
    const downloadAnchor = document.createElement("a");
    downloadAnchor.setAttribute("href", dataStr);
    downloadAnchor.setAttribute("download", `${activeEvent.name.toLowerCase().replace(/\s+/g, "_")}_plan.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();

    addToast({
      type: "info",
      title: "JSON Downloaded",
      message: "Full celebration plan exported as JSON.",
    });
  };

  const handleImportJson = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    const reader = new FileReader();
    reader.onload = (event) => {
      try {
        const parsed = JSON.parse(event.target?.result as string);
        if (!parsed.id || !parsed.name || !parsed.categories || !parsed.timeline) {
          throw new Error("Invalid Utsav event format");
        }

        const newId = `imported-${Date.now()}`;
        const importedPlan = {
          ...parsed,
          id: newId,
          name: `${parsed.name} (Imported)`,
        };

        saveNewEvent(importedPlan);
        addToast({
          type: "success",
          title: "Celebration Imported",
          message: `Successfully loaded ${importedPlan.name}.`,
        });
      } catch {
        addToast({
          type: "error",
          title: "Import Failed",
          message: "Selected file does not match Utsav celebration schema.",
        });
      }
    };
    reader.readAsText(file);
    e.target.value = "";
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div>
        <h1 className="font-display text-2xl sm:text-3xl font-bold text-ivory-100">
          Export &amp; Share Masterplan
        </h1>
        <p className="text-xs text-ivory-300 mt-1">
          Generate print-ready PDF sheets, export JSON backups, or copy markdown summaries
        </p>
      </div>

      {/* Grid of 3 Export Cards */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-5">
        {/* Print / PDF Card */}
        <div className="p-6 rounded-2xl bg-plum-900/40 border border-plum-700/50 backdrop-blur-md shadow-glass flex flex-col justify-between">
          <div>
            <div className="p-3 rounded-xl bg-plum-950 border border-plum-800 text-saffron-400 w-fit mb-4">
              <Printer className="w-6 h-6" />
            </div>
            <h2 className="font-display text-lg font-bold text-ivory-100">
              Print / Save as PDF
            </h2>
            <p className="text-xs text-ivory-300/80 leading-relaxed mt-2">
              Opens your browser print dialog with custom print styling designed for vendors, families, and coordinators.
            </p>
          </div>

          <button
            type="button"
            onClick={() => window.print()}
            className="mt-6 w-full py-2.5 rounded-xl bg-saffron-500 hover:bg-saffron-400 text-plum-950 font-bold text-xs flex items-center justify-center gap-2 transition-all focus:outline-none focus:ring-2 focus:ring-saffron-400"
          >
            <Printer className="w-4 h-4" />
            <span>Print Masterplan</span>
          </button>
        </div>

        {/* Copy Markdown Summary Card */}
        <div className="p-6 rounded-2xl bg-plum-900/40 border border-plum-700/50 backdrop-blur-md shadow-glass flex flex-col justify-between">
          <div>
            <div className="p-3 rounded-xl bg-plum-950 border border-plum-800 text-rose-400 w-fit mb-4">
              <FileText className="w-6 h-6" />
            </div>
            <h2 className="font-display text-lg font-bold text-ivory-100">
              Copy Text Summary
            </h2>
            <p className="text-xs text-ivory-300/80 leading-relaxed mt-2">
              Full formatted breakdown of budget, key milestones, and booked vendors for WhatsApp and family discussions.
            </p>
          </div>

          <button
            type="button"
            onClick={handleCopySummary}
            className="mt-6 w-full py-2.5 rounded-xl bg-plum-800 hover:bg-plum-700 text-ivory-100 font-bold text-xs flex items-center justify-center gap-2 transition-all focus:outline-none focus:ring-2 focus:ring-saffron-400"
          >
            {copiedSummary ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
            <span>{copiedSummary ? "Copied to Clipboard!" : "Copy Summary"}</span>
          </button>
        </div>

        {/* JSON Backup & Import Card */}
        <div className="p-6 rounded-2xl bg-plum-900/40 border border-plum-700/50 backdrop-blur-md shadow-glass flex flex-col justify-between">
          <div>
            <div className="p-3 rounded-xl bg-plum-950 border border-plum-800 text-purple-400 w-fit mb-4">
              <FileCode className="w-6 h-6" />
            </div>
            <h2 className="font-display text-lg font-bold text-ivory-100">
              JSON Backup &amp; Restore
            </h2>
            <p className="text-xs text-ivory-300/80 leading-relaxed mt-2">
              Export raw structured JSON data for offline safe keeping, or restore a previously exported plan.
            </p>
          </div>

          <div className="mt-6 flex gap-2">
            <button
              type="button"
              onClick={handleDownloadJson}
              className="flex-1 py-2.5 rounded-xl bg-plum-950 hover:bg-plum-800 text-ivory-200 border border-plum-700 font-semibold text-xs flex items-center justify-center gap-1.5 transition-colors"
            >
              <Download className="w-4 h-4" />
              <span>Export</span>
            </button>

            <button
              type="button"
              onClick={() => fileInputRef.current?.click()}
              className="flex-1 py-2.5 rounded-xl bg-plum-950 hover:bg-plum-800 text-ivory-200 border border-plum-700 font-semibold text-xs flex items-center justify-center gap-1.5 transition-colors"
            >
              <Upload className="w-4 h-4" />
              <span>Import</span>
            </button>
            <input
              ref={fileInputRef}
              type="file"
              accept=".json"
              onChange={handleImportJson}
              className="hidden"
            />
          </div>
        </div>
      </div>

      {/* Printable Preview Container (visible during window.print) */}
      <div className="print-only hidden p-8 bg-white text-black">
        <h1 className="text-3xl font-bold">{activeEvent.name}</h1>
        <p className="text-sm text-gray-700 mt-1">
          {formatDatePretty(activeEvent.date)} • {activeEvent.city} • {activeEvent.guestCount} Guests
        </p>

        <h2 className="text-xl font-bold mt-6 border-b pb-1">Budget Allocation</h2>
        <table className="w-full text-left text-sm mt-3 border-collapse">
          <thead>
            <tr className="border-b">
              <th className="py-2">Category</th>
              <th className="py-2">Allocated</th>
              <th className="py-2">Spent</th>
            </tr>
          </thead>
          <tbody>
            {activeEvent.categories.map((c) => (
              <tr key={c.id} className="border-b">
                <td className="py-1.5">{c.name}</td>
                <td className="py-1.5">{formatINR(c.allocatedAmount)}</td>
                <td className="py-1.5">{formatINR(c.spentAmount)}</td>
              </tr>
            ))}
          </tbody>
        </table>

        <h2 className="text-xl font-bold mt-6 border-b pb-1">Milestones &amp; Schedule</h2>
        <ul className="mt-3 space-y-2 text-sm">
          {activeEvent.timeline.map((t) => (
            <li key={t.id}>
              [{t.completed ? "✓" : " "}] <strong>{t.title}</strong> ({formatDatePretty(t.dueDate)}) - {t.description}
            </li>
          ))}
        </ul>

        <h2 className="text-xl font-bold mt-6 border-b pb-1">Vendor Contacts</h2>
        <ul className="mt-3 space-y-2 text-sm">
          {activeEvent.vendors.map((v) => (
            <li key={v.id}>
              <strong>{v.name}</strong> ({v.category}) — {v.status} | Price: {formatINR(v.quotedPrice)} | POC: {v.contactPerson || "N/A"} {v.phone || ""}
            </li>
          ))}
        </ul>
      </div>
    </div>
  );
}

